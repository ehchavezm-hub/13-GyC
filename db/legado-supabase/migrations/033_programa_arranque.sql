-- ── Tablas ───────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS programa_arranque_items (
  id           SERIAL PRIMARY KEY,
  item_codigo  TEXT NOT NULL UNIQUE,          -- '1', '1a', '1b', '2', ...
  proceso      TEXT NOT NULL,
  area_lider   TEXT NOT NULL,
  obligatorio  BOOLEAN NOT NULL DEFAULT false,
  descripcion  TEXT NOT NULL,
  orden        INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS programa_arranque (
  id                       UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  proyecto_id              UUID NOT NULL REFERENCES proyectos(id) ON DELETE CASCADE,
  cr_proyecto              TEXT,
  fecha_movilizacion       DATE,
  fecha_construccion       DATE,
  fecha_actualizacion      DATE,
  num_semanas              INTEGER NOT NULL DEFAULT 8,
  created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (proyecto_id)
);

CREATE TABLE IF NOT EXISTS programa_arranque_detalle (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  programa_id  UUID NOT NULL REFERENCES programa_arranque(id) ON DELETE CASCADE,
  item_codigo  TEXT NOT NULL REFERENCES programa_arranque_items(item_codigo),
  responsable  TEXT,
  fecha_plan   DATE,
  fecha_real   DATE,
  comentarios  TEXT,
  semanas      JSONB NOT NULL DEFAULT '[]',  -- [{plan:bool,cumplio:bool}, ...]
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (programa_id, item_codigo)
);

CREATE INDEX IF NOT EXISTS idx_prog_arr_proyecto ON programa_arranque(proyecto_id);
CREATE INDEX IF NOT EXISTS idx_prog_arr_det_prog ON programa_arranque_detalle(programa_id);

